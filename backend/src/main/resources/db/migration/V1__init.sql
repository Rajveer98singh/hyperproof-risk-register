-- Core Risk Register schema.
-- Written in portable SQL that runs unchanged on H2 (PostgreSQL mode) and real PostgreSQL.
-- Scores (inherent/residual/severity) are intentionally NOT stored: they are pure functions of
-- the raw inputs below and are always derived on read, so they can never go stale.

CREATE TABLE risk (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(255) NOT NULL,
    -- owner and description are encrypted at rest (AES-GCM) -> stored as base64 ciphertext (TEXT).
    description      TEXT,
    category         VARCHAR(32)  NOT NULL,
    owner            TEXT,
    likelihood       INT          NOT NULL CHECK (likelihood BETWEEN 1 AND 5),
    impact           INT          NOT NULL CHECK (impact     BETWEEN 1 AND 5),
    status           VARCHAR(32)  NOT NULL,
    next_review_date DATE,
    version          BIGINT       NOT NULL DEFAULT 0,   -- optimistic locking
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE mitigation (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    risk_id       BIGINT       NOT NULL REFERENCES risk (id) ON DELETE CASCADE,
    description   TEXT         NOT NULL,
    effectiveness INT          NOT NULL CHECK (effectiveness BETWEEN 1 AND 5),
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Indexes on the columns we filter by (category, status) and the mitigation FK.
CREATE INDEX idx_risk_category      ON risk (category);
CREATE INDEX idx_risk_status        ON risk (status);
CREATE INDEX idx_mitigation_risk_id ON mitigation (risk_id);
