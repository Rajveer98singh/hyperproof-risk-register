-- Compliance-framework catalog (reference data) + many-to-many mapping to risks.
-- Stretch goal: map a risk to NIST CSF functions and/or SOC 2 Trust Service Criteria.

CREATE TABLE framework_control (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    framework   VARCHAR(32)  NOT NULL,   -- 'NIST_CSF' | 'SOC2'
    code        VARCHAR(32)  NOT NULL,   -- e.g. 'PR', 'CC6'
    name        VARCHAR(128) NOT NULL,
    CONSTRAINT uq_framework_control UNIQUE (framework, code)
);

CREATE TABLE risk_framework (
    risk_id              BIGINT NOT NULL REFERENCES risk (id) ON DELETE CASCADE,
    framework_control_id BIGINT NOT NULL REFERENCES framework_control (id) ON DELETE CASCADE,
    PRIMARY KEY (risk_id, framework_control_id)
);

